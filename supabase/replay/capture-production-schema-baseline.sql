-- Read-only, schema-only capture for the public application schema.
--
-- This query emits one JSON object. `baseline_sql` contains DDL only: no COPY,
-- INSERT, UPDATE, DELETE, sequence values, or table rows. The caller must refuse
-- the result when `preflight_issues` is non-empty and must independently scan the
-- returned DDL for credential-shaped material before writing it to disk.
--
-- Managed Supabase schemas and roles are deliberately outside this capture. The
-- isolated replay creates their minimum contract in 00_platform_bootstrap.sql.
-- The captured application boundary is every non-extension-owned object in the
-- public schema plus its constraints, indexes, functions, views, triggers, RLS,
-- policies, comments, and effective object ACLs for the API roles.

with recursive
capture as (
  select
    clock_timestamp() as captured_at,
    current_setting('server_version_num') as server_version_num,
    coalesce((select max(version) from supabase_migrations.schema_migrations), '') as watermark,
    (select count(*) from supabase_migrations.schema_migrations) as migration_row_count
),
public_tables as (
  select c.*
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('r', 'p')
    and not exists (
      select 1
      from pg_catalog.pg_depend d
      where d.classid = 'pg_class'::regclass
        and d.objid = c.oid
        and d.deptype = 'e'
    )
),
public_views as (
  select c.*
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('v', 'm')
    and not exists (
      select 1
      from pg_catalog.pg_depend d
      where d.classid = 'pg_class'::regclass
        and d.objid = c.oid
        and d.deptype = 'e'
    )
),
public_functions as (
  select p.*
  from pg_catalog.pg_proc p
  join pg_catalog.pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and not exists (
      select 1
      from pg_catalog.pg_depend d
      where d.classid = 'pg_proc'::regclass
        and d.objid = p.oid
        and d.deptype = 'e'
    )
),
identity_sequence as (
  select
    a.attrelid,
    a.attnum,
    sn.nspname as sequence_schema,
    seq.relname as sequence_name,
    s.seqstart,
    s.seqincrement,
    s.seqmin,
    s.seqmax,
    s.seqcache,
    s.seqcycle
  from pg_catalog.pg_attribute a
  join pg_catalog.pg_depend dep
    on dep.refclassid = 'pg_class'::regclass
   and dep.refobjid = a.attrelid
   and dep.refobjsubid = a.attnum
   and dep.classid = 'pg_class'::regclass
   and dep.deptype = 'i'
  join pg_catalog.pg_class seq on seq.oid = dep.objid and seq.relkind = 'S'
  join pg_catalog.pg_namespace sn on sn.oid = seq.relnamespace
  join pg_catalog.pg_sequence s on s.seqrelid = seq.oid
  where a.attidentity <> ''
),
column_sql as (
  select
    a.attrelid,
    a.attnum,
    format(
      '%I %s%s%s%s%s',
      a.attname,
      pg_catalog.format_type(a.atttypid, a.atttypmod),
      case
        when a.attcollation <> 0 and a.attcollation <> t.typcollation
          then format(' COLLATE %I.%I', cn.nspname, coll.collname)
        else ''
      end,
      case a.attidentity
        when 'a' then format(
          ' GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME %I.%I START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s %s)',
          ids.sequence_schema, ids.sequence_name, ids.seqstart, ids.seqincrement,
          ids.seqmin, ids.seqmax, ids.seqcache,
          case when ids.seqcycle then 'CYCLE' else 'NO CYCLE' end
        )
        when 'd' then format(
          ' GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME %I.%I START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s %s)',
          ids.sequence_schema, ids.sequence_name, ids.seqstart, ids.seqincrement,
          ids.seqmin, ids.seqmax, ids.seqcache,
          case when ids.seqcycle then 'CYCLE' else 'NO CYCLE' end
        )
        else ''
      end,
      case
        when a.attgenerated = 's'
          then format(' GENERATED ALWAYS AS (%s) STORED', pg_catalog.pg_get_expr(ad.adbin, ad.adrelid, true))
        when a.attidentity = '' and ad.oid is not null
          then format(' DEFAULT %s', pg_catalog.pg_get_expr(ad.adbin, ad.adrelid, true))
        else ''
      end,
      case when a.attnotnull then ' NOT NULL' else '' end
    ) as definition
  from pg_catalog.pg_attribute a
  join public_tables c on c.oid = a.attrelid
  join pg_catalog.pg_type t on t.oid = a.atttypid
  left join pg_catalog.pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  left join identity_sequence ids on ids.attrelid = a.attrelid and ids.attnum = a.attnum
  left join pg_catalog.pg_collation coll on coll.oid = a.attcollation
  left join pg_catalog.pg_namespace cn on cn.oid = coll.collnamespace
  where a.attnum > 0 and not a.attisdropped
),
table_ddl as (
  select
    20 as phase,
    c.relname as sort_key,
    format(
      'CREATE TABLE public.%I (%s%s)%s;',
      c.relname,
      E'\n    ',
      string_agg(cs.definition, E',\n    ' order by cs.attnum),
      case when c.reloptions is null then '' else format(E'\nWITH (%s)', array_to_string(c.reloptions, ', ')) end
    ) as ddl
  from public_tables c
  join column_sql cs on cs.attrelid = c.oid
  group by c.oid, c.relname, c.reloptions
),
function_ddl as (
  select
    30 as phase,
    format('%I.%I(%s)', 'public', p.proname, pg_catalog.pg_get_function_identity_arguments(p.oid)) as sort_key,
    pg_catalog.pg_get_functiondef(p.oid) || ';' as ddl
  from public_functions p
),
constraint_ddl as (
  select
    40 as phase,
    format('%s:%s:%s', case when co.contype = 'f' then '2' else '1' end, c.relname, co.conname) as sort_key,
    format(
      'ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;',
      c.relname,
      co.conname,
      pg_catalog.pg_get_constraintdef(co.oid, true)
    ) as ddl
  from pg_catalog.pg_constraint co
  join public_tables c on c.oid = co.conrelid
  where co.conparentid = 0
),
index_ddl as (
  select
    50 as phase,
    ic.relname as sort_key,
    pg_catalog.pg_get_indexdef(i.indexrelid, 0, true) || ';' as ddl
  from pg_catalog.pg_index i
  join public_tables c on c.oid = i.indrelid
  join pg_catalog.pg_class ic on ic.oid = i.indexrelid
  where not exists (
    select 1 from pg_catalog.pg_constraint co where co.conindid = i.indexrelid
  )
),
view_edges as (
  select distinct v.oid as view_oid, dep.refobjid as dependency_oid
  from public_views v
  join pg_catalog.pg_rewrite rw on rw.ev_class = v.oid and rw.rulename = '_RETURN'
  join pg_catalog.pg_depend dep
    on dep.classid = 'pg_rewrite'::regclass
   and dep.objid = rw.oid
   and dep.refclassid = 'pg_class'::regclass
  join public_views dependency on dependency.oid = dep.refobjid
  where dep.refobjid <> v.oid
),
view_reach(view_oid, dependency_oid, depth) as (
  select view_oid, dependency_oid, 1 from view_edges
  union all
  select r.view_oid, e.dependency_oid, r.depth + 1
  from view_reach r
  join view_edges e on e.view_oid = r.dependency_oid
  where r.depth < 64
),
view_depth as (
  select v.oid, coalesce(max(r.depth), 0) as depth
  from public_views v
  left join view_reach r on r.view_oid = v.oid
  group by v.oid
),
view_ddl as (
  select
    60 as phase,
    format('%04s:%s', d.depth, v.relname) as sort_key,
    format(
      'CREATE VIEW public.%I%s AS%s%s;',
      v.relname,
      case when v.reloptions is null then '' else format(' WITH (%s)', array_to_string(v.reloptions, ', ')) end,
      E'\n',
      pg_catalog.pg_get_viewdef(v.oid, true)
    ) as ddl
  from public_views v
  join view_depth d on d.oid = v.oid
),
trigger_ddl as (
  select
    70 as phase,
    format('%s:%s', c.relname, t.tgname) as sort_key,
    pg_catalog.pg_get_triggerdef(t.oid, true) || ';' as ddl
  from pg_catalog.pg_trigger t
  join public_tables c on c.oid = t.tgrelid
  where not t.tgisinternal
),
rls_ddl as (
  select
    80 as phase,
    c.relname as sort_key,
    format(
      'ALTER TABLE public.%I %s ROW LEVEL SECURITY;%sALTER TABLE public.%I %s FORCE ROW LEVEL SECURITY;',
      c.relname,
      case when c.relrowsecurity then 'ENABLE' else 'DISABLE' end,
      E'\n',
      c.relname,
      case when c.relforcerowsecurity then '' else 'NO' end
    ) as ddl
  from public_tables c
),
policy_ddl as (
  select
    90 as phase,
    format('%s:%s', c.relname, p.polname) as sort_key,
    format(
      'CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;',
      p.polname,
      c.relname,
      case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
      case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
      (select string_agg(case when role_oid = 0 then 'PUBLIC' else pg_catalog.quote_ident(r.rolname) end, ', ' order by role_oid)
       from unnest(p.polroles) role_oid
       left join pg_catalog.pg_roles r on r.oid = role_oid),
      case when p.polqual is null then '' else format(' USING (%s)', pg_catalog.pg_get_expr(p.polqual, p.polrelid, true)) end,
      case when p.polwithcheck is null then '' else format(' WITH CHECK (%s)', pg_catalog.pg_get_expr(p.polwithcheck, p.polrelid, true)) end
    ) as ddl
  from pg_catalog.pg_policy p
  join public_tables c on c.oid = p.polrelid
),
comment_ddl as (
  select 95 as phase, '00:schema' as sort_key,
         format('COMMENT ON SCHEMA public IS %L;', pg_catalog.obj_description(n.oid, 'pg_namespace')) as ddl
  from pg_catalog.pg_namespace n
  where n.nspname = 'public' and pg_catalog.obj_description(n.oid, 'pg_namespace') is not null
  union all
  select 95, format('10:%s:%04s', c.relname, a.attnum),
         format('COMMENT ON COLUMN public.%I.%I IS %L;', c.relname, a.attname, pg_catalog.col_description(c.oid, a.attnum))
  from pg_catalog.pg_attribute a
  join pg_catalog.pg_class c on c.oid = a.attrelid
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and a.attnum > 0 and not a.attisdropped
    and pg_catalog.col_description(c.oid, a.attnum) is not null
  union all
  select 95, format('20:%s', p.oid::regprocedure::text),
         format(
           'COMMENT ON FUNCTION public.%I(%s) IS %L;',
           p.proname,
           pg_catalog.pg_get_function_identity_arguments(p.oid),
           pg_catalog.obj_description(p.oid, 'pg_proc')
         )
  from public_functions p
  where pg_catalog.obj_description(p.oid, 'pg_proc') is not null
),
relation_acl_reset as (
  select
    100 as phase,
    format('00:%s:%s', c.relname, role_name) as sort_key,
    format(
      'REVOKE ALL PRIVILEGES ON %s public.%I FROM %s;',
      case when c.relkind = 'S' then 'SEQUENCE' else 'TABLE' end,
      c.relname,
      case when role_name = 'PUBLIC' then 'PUBLIC' else pg_catalog.quote_ident(role_name) end
    ) as ddl
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  cross join (values ('PUBLIC'), ('anon'), ('authenticated'), ('service_role')) roles(role_name)
  where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm', 'S')
    and not exists (
      select 1 from pg_catalog.pg_depend d
      where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype = 'e'
    )
),
relation_acl_grant as (
  select
    101 as phase,
    format('10:%s:%s:%s:%s', c.relname, coalesce(grantee.rolname, 'PUBLIC'), x.privilege_type, x.is_grantable) as sort_key,
    format(
      'GRANT %s ON %s public.%I TO %s%s;',
      x.privilege_type,
      case when c.relkind = 'S' then 'SEQUENCE' else 'TABLE' end,
      c.relname,
      case when x.grantee = 0 then 'PUBLIC' else pg_catalog.quote_ident(grantee.rolname) end,
      case when x.is_grantable then ' WITH GRANT OPTION' else '' end
    ) as ddl
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  cross join lateral pg_catalog.aclexplode(
    coalesce(c.relacl, pg_catalog.acldefault(case when c.relkind = 'S' then 'S'::"char" else 'r'::"char" end, c.relowner))
  ) x
  left join pg_catalog.pg_roles grantee on grantee.oid = x.grantee
  where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm', 'S')
    and x.grantee <> c.relowner
    and (x.grantee = 0 or grantee.rolname in ('anon', 'authenticated', 'service_role'))
    and not exists (
      select 1 from pg_catalog.pg_depend d
      where d.classid = 'pg_class'::regclass and d.objid = c.oid and d.deptype = 'e'
    )
),
function_acl_reset as (
  select
    102 as phase,
    format('20:%s:%s', p.oid::regprocedure::text, role_name) as sort_key,
    format(
      'REVOKE ALL PRIVILEGES ON FUNCTION public.%I(%s) FROM %s;',
      p.proname,
      pg_catalog.pg_get_function_identity_arguments(p.oid),
      case when role_name = 'PUBLIC' then 'PUBLIC' else pg_catalog.quote_ident(role_name) end
    ) as ddl
  from public_functions p
  cross join (values ('PUBLIC'), ('anon'), ('authenticated'), ('service_role')) roles(role_name)
),
function_acl_grant as (
  select
    103 as phase,
    format('30:%s:%s:%s', p.oid::regprocedure::text, coalesce(grantee.rolname, 'PUBLIC'), x.is_grantable) as sort_key,
    format(
      'GRANT %s ON FUNCTION public.%I(%s) TO %s%s;',
      x.privilege_type,
      p.proname,
      pg_catalog.pg_get_function_identity_arguments(p.oid),
      case when x.grantee = 0 then 'PUBLIC' else pg_catalog.quote_ident(grantee.rolname) end,
      case when x.is_grantable then ' WITH GRANT OPTION' else '' end
    ) as ddl
  from public_functions p
  cross join lateral pg_catalog.aclexplode(coalesce(p.proacl, pg_catalog.acldefault('f', p.proowner))) x
  left join pg_catalog.pg_roles grantee on grantee.oid = x.grantee
  where x.grantee <> p.proowner
    and (x.grantee = 0 or grantee.rolname in ('anon', 'authenticated', 'service_role'))
),
schema_acl_reset as (
  select 5 as phase, format('00:%s', role_name) as sort_key,
         format('REVOKE ALL PRIVILEGES ON SCHEMA public FROM %s;', case when role_name = 'PUBLIC' then 'PUBLIC' else pg_catalog.quote_ident(role_name) end) as ddl
  from (values ('PUBLIC'), ('anon'), ('authenticated'), ('service_role')) roles(role_name)
),
schema_acl_grant as (
  select
    6 as phase,
    format('10:%s:%s', coalesce(grantee.rolname, 'PUBLIC'), x.privilege_type) as sort_key,
    format(
      'GRANT %s ON SCHEMA public TO %s%s;',
      x.privilege_type,
      case when x.grantee = 0 then 'PUBLIC' else pg_catalog.quote_ident(grantee.rolname) end,
      case when x.is_grantable then ' WITH GRANT OPTION' else '' end
    ) as ddl
  from pg_catalog.pg_namespace n
  cross join lateral pg_catalog.aclexplode(coalesce(n.nspacl, pg_catalog.acldefault('n', n.nspowner))) x
  left join pg_catalog.pg_roles grantee on grantee.oid = x.grantee
  where n.nspname = 'public'
    and x.grantee <> n.nspowner
    and (x.grantee = 0 or grantee.rolname in ('anon', 'authenticated', 'service_role', 'pg_database_owner', 'postgres'))
),
statements as (
  select 1 as phase, '00:preamble' as sort_key,
         E'SET check_function_bodies = false;\nSET search_path = "$user", public, extensions;' as ddl
  union all select * from schema_acl_reset
  union all select * from schema_acl_grant
  union all select * from table_ddl
  union all select * from function_ddl
  union all select * from constraint_ddl
  union all select * from index_ddl
  union all select * from view_ddl
  union all select * from trigger_ddl
  union all select * from rls_ddl
  union all select * from policy_ddl
  union all select * from comment_ddl
  union all select * from relation_acl_reset
  union all select * from relation_acl_grant
  union all select * from function_acl_reset
  union all select * from function_acl_grant
  union all select 999, '99:postamble', E'RESET check_function_bodies;\nRESET search_path;'
),
body as (
  select string_agg(ddl, E'\n\n' order by phase, sort_key) || E'\n' as baseline_sql
  from statements
),
unsupported as (
  select issue
  from (
    values
      ('partitioned_table', (select count(*) from public_tables where relkind = 'p')),
      ('nonpermanent_table', (select count(*) from public_tables where relpersistence <> 'p')),
      ('materialized_view', (select count(*) from public_views where relkind = 'm')),
      ('public_enum_or_domain', (select count(*) from pg_catalog.pg_type t join pg_catalog.pg_namespace n on n.oid=t.typnamespace where n.nspname='public' and t.typtype in ('e','d'))),
      ('inheritance_edge', (select count(*) from pg_catalog.pg_inherits i join public_tables c on c.oid=i.inhrelid)),
      ('column_acl', (select count(*) from pg_catalog.pg_attribute a join public_tables c on c.oid=a.attrelid where a.attnum > 0 and a.attacl is not null)),
      ('custom_rule', (select count(*) from pg_catalog.pg_rewrite r join pg_catalog.pg_class c on c.oid=r.ev_class join pg_catalog.pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and r.rulename <> '_RETURN')),
      ('extended_statistics', (select count(*) from pg_catalog.pg_statistic_ext s join pg_catalog.pg_namespace n on n.oid=s.stxnamespace where n.nspname='public')),
      ('non_function_routine', (select count(*) from public_functions where prokind <> 'f')),
      ('invalid_index', (select count(*) from pg_catalog.pg_index i join public_tables c on c.oid=i.indrelid where not i.indisvalid or not i.indisready)),
      ('unsupported_acl_grantee', (
        select count(*)
        from (
          select x.grantee, c.relowner as owner
          from pg_catalog.pg_class c
          join pg_catalog.pg_namespace n on n.oid=c.relnamespace
          cross join lateral pg_catalog.aclexplode(coalesce(c.relacl, pg_catalog.acldefault(case when c.relkind='S' then 'S'::"char" else 'r'::"char" end,c.relowner))) x
          where n.nspname='public' and c.relkind in ('r','p','v','m','S')
          union all
          select x.grantee, p.proowner
          from public_functions p
          cross join lateral pg_catalog.aclexplode(coalesce(p.proacl,pg_catalog.acldefault('f',p.proowner))) x
        ) a
        left join pg_catalog.pg_roles r on r.oid=a.grantee
        where a.grantee <> a.owner and a.grantee <> 0 and r.rolname not in ('anon','authenticated','service_role')
      ))
  ) checks(issue, count)
  where count <> 0
),
sensitive as (
  select kind, identity
  from (
    select 'function'::text as kind, p.oid::regprocedure::text as identity, pg_catalog.pg_get_functiondef(p.oid) as content
    from public_functions p
    union all
    select 'view', format('public.%I', v.relname), pg_catalog.pg_get_viewdef(v.oid, true)
    from public_views v
    union all
    select 'trigger', format('public.%I:%I', c.relname, t.tgname), pg_catalog.pg_get_triggerdef(t.oid, true)
    from pg_catalog.pg_trigger t join public_tables c on c.oid=t.tgrelid where not t.tgisinternal
    union all
    select 'policy', format('public.%I:%I', c.relname, p.polname),
           concat_ws(E'\n', pg_catalog.pg_get_expr(p.polqual,p.polrelid,true), pg_catalog.pg_get_expr(p.polwithcheck,p.polrelid,true))
    from pg_catalog.pg_policy p join public_tables c on c.oid=p.polrelid
  ) definitions
  where content ~* '(-----BEGIN[[:space:]]+(RSA[[:space:]]+|EC[[:space:]]+|OPENSSH[[:space:]]+)?PRIVATE[[:space:]]+KEY-----|eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}|sb_secret_[A-Za-z0-9_-]+|postgres(ql)?://[^[:space:]''"]+:[^[:space:]''"]+@|AKIA[0-9A-Z]{16})'
)
select jsonb_build_object(
  'captured_at', capture.captured_at,
  'server_version_num', capture.server_version_num,
  'watermark', capture.watermark,
  'migration_row_count', capture.migration_row_count,
  'scope', 'public-application-schema-v1',
  'table_count', (select count(*) from public_tables),
  'column_count', (select count(*) from column_sql),
  'view_count', (select count(*) from public_views),
  'function_count', (select count(*) from public_functions),
  'constraint_count', (select count(*) from constraint_ddl),
  'index_count', (select count(*) from index_ddl),
  'trigger_count', (select count(*) from trigger_ddl),
  'policy_count', (select count(*) from policy_ddl),
  'comment_count', (select count(*) from comment_ddl),
  'preflight_issues', coalesce((select jsonb_agg(issue order by issue) from unsupported), '[]'::jsonb),
  'sensitive_definition_count', (select count(*) from sensitive),
  'sensitive_objects', coalesce((select jsonb_agg(jsonb_build_object('kind',kind,'identity',identity) order by kind,identity) from sensitive), '[]'::jsonb),
  'body_sha256', encode(extensions.digest(convert_to(body.baseline_sql, 'UTF8'), 'sha256'), 'hex'),
  'body_bytes', octet_length(convert_to(body.baseline_sql, 'UTF8')),
  'baseline_sql', body.baseline_sql
) as capture
from capture cross join body;
