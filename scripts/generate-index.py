#!/usr/bin/env python3
"""generate-index.py — Generate INDEX.md from root + docs/ .md files.

Scans the project root and docs/ directory recursively for .md files.
For each file, extracts a one-line description from the first meaningful
heading or filename stem, and checks git log for last modification date.
Files not modified in the last 30 days are marked "可能过期".

Output: INDEX.md in the project root.
"""

import os
import re
import subprocess
import sys
from datetime import datetime, timezone, timedelta
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
CUTOFF_DAYS = 30
NOW = datetime.now(timezone.utc)

# ── Helpers ──────────────────────────────────────────────────────────────────


def git_last_modified(relpath: str) -> datetime | None:
    """Return the last commit date (UTC) for a file, or None if not tracked."""
    try:
        result = subprocess.run(
            ["git", "log", "-1", "--format=%aI", "--", relpath],
            cwd=PROJECT_DIR,
            capture_output=True,
            text=True,
            timeout=10,
        )
        if result.returncode != 0 or not result.stdout.strip():
            return None
        return datetime.fromisoformat(result.stdout.strip())
    except Exception:
        return None


def describe_file(filepath: Path) -> str:
    """Extract a one-line description from the file."""
    try:
        content = filepath.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return _stem_desc(filepath)

    # Try the first heading (# ...)
    for line in content.splitlines():
        stripped = line.strip()
        m = re.match(r"^#\s+(.+)", stripped)
        if m:
            desc = m.group(1).strip()
            # Remove markdown links, keep text
            desc = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", desc)
            if len(desc) > 80:
                desc = desc[:77] + "..."
            return desc

    # Try first non-empty, non-comment, non-hr line
    for line in content.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("<!--") or stripped.startswith("---"):
            continue
        if stripped.startswith("#"):
            continue
        desc = stripped[:80]
        if len(stripped) > 80:
            desc += "..."
        return desc

    return _stem_desc(filepath)


def _stem_desc(filepath: Path) -> str:
    stem = filepath.stem
    # Convert kebab/snake to spaces, capitalize
    desc = stem.replace("-", " ").replace("_", " ").strip()
    return desc[:80]


def status_label(dt: datetime | None) -> str:
    if dt is None:
        return "未跟踪"
    age = NOW - dt
    if age > timedelta(days=CUTOFF_DAYS):
        return "可能过期"
    return "最新"


def fmt_date(dt: datetime | None) -> str:
    if dt is None:
        return "N/A"
    return dt.strftime("%Y-%m-%d")


# ── Main ─────────────────────────────────────────────────────────────────────


def collect_md_files() -> list[Path]:
    """Collect .md files from project root (non-recursive) and docs/ (recursive)."""
    files: list[Path] = []

    # Root-level .md files (non-recursive)
    for entry in sorted(PROJECT_DIR.iterdir()):
        if entry.is_file() and entry.suffix == ".md":
            files.append(entry)

    # docs/ directory (recursive)
    docs_dir = PROJECT_DIR / "docs"
    if docs_dir.is_dir():
        for entry in sorted(docs_dir.rglob("*.md")):
            files.append(entry)

    return files


def generate_index():
    md_files = collect_md_files()

    lines: list[str] = []
    lines.append("<!-- auto-generated by scripts/generate-index.py, edit with caution -->")
    lines.append("")
    lines.append("# INDEX — 项目文档索引")
    lines.append("")
    lines.append(f"生成时间：{NOW.strftime('%Y-%m-%d %H:%M UTC')}  |  文件数：{len(md_files)}  |  过期阈值：{CUTOFF_DAYS}天")
    lines.append("")
    lines.append("| 文件 | 描述 | 最后更新 | 状态 |")
    lines.append("|------|------|---------|------|")

    for fp in md_files:
        rel = fp.relative_to(PROJECT_DIR)
        desc = describe_file(fp)
        last_dt = git_last_modified(str(rel))
        date_str = fmt_date(last_dt)
        status = status_label(last_dt)

        lines.append(f"| {rel} | {desc} | {date_str} | {status} |")

    output_path = PROJECT_DIR / "INDEX.md"
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated INDEX.md with {len(md_files)} entries → {output_path}")


if __name__ == "__main__":
    generate_index()
