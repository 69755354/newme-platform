begin;

-- ---------------------------------------------------------------------------
-- public.meta_tokens — singleton row holding the Meta/Facebook API access
-- token in plaintext.
--
-- 20260701000002_final_for_all_cleanup.sql:153 does an unguarded
-- `CREATE POLICY ... ON meta_tokens`, and src/app/api/meta/oauth-callback
-- upserts into it. No migration creates the table. Its RLS posture is fixed by
-- 20260811100200_f10_meta_tokens_drop_permissive_select.sql; without this
-- declaration that migration could not be replayed anywhere.
-- ---------------------------------------------------------------------------
create table if not exists public.meta_tokens (
  id           bigint generated by default as identity primary key,
  access_token text        not null,
  created_at   timestamptz default now(),
  expires_at   timestamptz
);

alter table public.meta_tokens enable row level security;

-- ---------------------------------------------------------------------------
-- public.profiles.password_changed_at / force_password_change
--
-- Read by src/app/api/auth/me and src/proxy.ts to reject a token minted before
-- a password change; written by src/app/api/auth/change-password. Both appear in
-- the generated types. No migration adds either. The L0 revocation work depends
-- on them.
-- ---------------------------------------------------------------------------
alter table public.profiles
  add column if not exists password_changed_at   timestamptz;
alter table public.profiles
  add column if not exists force_password_change boolean default false;

-- ---------------------------------------------------------------------------
-- public.leads.rep_name
--
-- Selected by the lead_alerts view in 20260602010000_crm_mvp_final.sql:112,
-- 20260613010000_lead_alerts_v2.sql:18 and
-- 20260613020000_fix_alerts_and_constraints.sql:51, and backfilled into
-- leads.owner by 20260602020000_crm_fix_owner_policies.sql:8. Three migrations
-- and a production view depend on a column no migration declares.
-- ---------------------------------------------------------------------------
alter table public.leads
  add column if not exists rep_name text;

commit;
