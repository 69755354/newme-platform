export function bugTitle(id) {
  return BUGS[id] || "(未登记的问题编号)";
}

/** Extract bug ids from Playwright tags like "@bug-4a-1". */
export function bugIdsFromTags(tags = []) {
  return tags
    .map((t) => String(t).replace(/^@/, ""))
    .filter((t) => t.startsWith("bug-"))
    .map((t) => t.slice(4));
}

